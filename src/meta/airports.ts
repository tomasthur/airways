/** World airport network for the map hub. Positions are WGS84 for SVG projection. */

export type AirportStatus = 'home' | 'open' | 'locked';

/** Index into the terminal shell catalog (distinct silhouettes). */
export type AirportShellId = 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7;

/** Career unlock tier — 0 is the free Central Europe starter set. */
export type AirportTier = 0 | 1 | 2 | 3;

export type AirportRegion = 'ce' | 'europe' | 'americas' | 'mena' | 'asia' | 'oceania';

export interface Airport {
  id: string;
  iata: string;
  city: string;
  name: string;
  lat: number;
  lon: number;
  /** Terminal shell silhouette 0..7. */
  shell: AirportShellId;
  /** Painted on the in-world terminal building. */
  terminalTitle: string;
  tier: AirportTier;
  region: AirportRegion;
  /** One-time clearance cost in credits; 0 = starter. */
  unlockCost: number;
  /** Short copy when selected as a destination. */
  brief?: string;
  /** Shown when the player taps a locked airport. */
  lockHint?: string;
}

